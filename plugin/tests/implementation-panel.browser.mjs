import assert from 'node:assert/strict'

// Only run with the isolated fictional Worker, never launch a real repair.
export async function exerciseImplementationPanel({ evaluate, wait, screenshot }) {
  const click = label => evaluate(`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent===${JSON.stringify(label)});if(!b||b.disabled)throw Error('Unavailable button: '+${JSON.stringify(label)});b.click()})()`)
  const configure = input => evaluate(`orca.host.call('plugin.request',{name:'fixture.implementation',input:${JSON.stringify(input)}})`)
  const contains = value => `document.body.innerText.includes(${JSON.stringify(value)})`
  await click('实施')
  await wait(contains('暂无匹配的执行记录'))
  await screenshot('implementation-empty', 'light', 360)
  await configure({ seeded: true })
  await click('我的 Bug')
  await click('实施')
  await wait(contains('session-fixture-only'))
  assert.equal(await evaluate(contains('虚构已关闭缺陷')), true)
  assert.equal(await evaluate(contains('待核实 · 启动或发送结果不明')), true)
  assert.equal(await evaluate(`document.documentElement.scrollWidth>innerWidth`), false)
  await screenshot('implementation-list-light', 'light', 460)
  await screenshot('implementation-list-dark-narrow', 'dark', 360)
  await click('查看 Bug 详情')
  await wait(contains('正文末尾'))
  await click('返回执行记录')
  await wait(contains('session-fixture-only'))
  await click('查看 Bug 详情')
  await wait(contains('正文末尾'))
  await click('实施')
  await wait(contains('刷新执行记录'))
  assert.equal(await evaluate(contains('正文末尾')), false)
  await configure({ seeded: true, error: true })
  await click('刷新执行记录')
  await wait(contains('执行记录加载失败'))
  assert.equal(await evaluate(contains('session-fixture-only')), false)
  await screenshot('implementation-error', 'dark', 360)
  await configure({ seeded: true })
  await click('刷新执行记录')
  await wait(contains('session-fixture-only'))
  await configure({ seeded: true, delay: 200 })
  await click('刷新执行记录')
  await click('我的 Bug')
  await wait(`!!document.querySelector('button.bug-item')`)
  await evaluate(`new Promise(resolve=>setTimeout(resolve,300))`)
  assert.equal(await evaluate(`document.querySelector('[role=tab][aria-selected=true]').textContent`), '我的 Bug')
  const calls = await evaluate(`orca.host.call('plugin.request',{name:'fixture.calls',input:{}}).then(r=>r.output.value.calls)`)
  assert.equal(calls.filter(name=>name==='repair.start'||name==='repair.prepare').length, 0)
  return { directTab: true, existingRecords: true, includesClosed: true, detailReturn: true, sameTabReturnsList: true, refreshFailureRecovery: true, staleResponseIgnored: true, noRepairLaunch: true }
}
