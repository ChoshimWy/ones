import assert from 'node:assert/strict'
// Only call against the fictional html-worker fixture, never a production account.
export async function exerciseRepairPanel({ evaluate, wait, screenshot }) {
  const click = label => evaluate(`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent===${JSON.stringify(label)});if(!b||b.disabled)throw Error('Unavailable button');b.click()})()`)
  await evaluate(`document.querySelector('button.bug-item').click()`)
  await wait(`!!document.querySelector('h2') && document.body.innerText.includes('正文末尾')`)
  assert.equal(await evaluate(`[...document.querySelectorAll('button')].filter(b=>b.textContent==='执行修复').length`), 2)
  const geometry = await evaluate(`(()=>{const row=document.querySelector('.detail-actions'),buttons=row.querySelectorAll('button'),a=buttons[0].getBoundingClientRect(),b=buttons[1].getBoundingClientRect();return {sameRow:Math.abs(a.top-b.top)<1,right:b.right>a.right,overflow:document.documentElement.scrollWidth>innerWidth}})()`)
  assert.deepEqual(geometry, { sameRow: true, right: true, overflow: false })
  await screenshot('ones-repair-detail', 'light', 460)
  await click('执行修复')
  await wait(`document.body.innerText.includes('自动匹配：本地虚构项目')`)
  assert.equal(await evaluate(`!!document.getElementById('本地项目')`), false)
  await screenshot('ones-repair-confirm', 'dark', 460)
  await screenshot('ones-repair-narrow', 'light', 360)
  assert.equal(await evaluate(`document.documentElement.scrollWidth>innerWidth`), false)
  await click('创建聊天并发送')
  await wait(`document.body.innerText.includes('session-fixture-only')`)
  assert.equal(await evaluate(`document.body.innerText.includes('CLI 暂不支持打开指定 session')`), true)
  await screenshot('ones-repair-receipt', 'dark', 460)
  await click('刷新详情')
  await wait(`document.body.innerText.includes('正文末尾') && document.querySelectorAll('.detail-footer button').length===1`)
  await evaluate(`document.querySelector('.detail-footer button').click()`)
  await wait(`document.body.innerText.includes('自动匹配：本地虚构项目')`)
  await click('取消')
  await evaluate(`orca.host.call('plugin.request',{name:'fixture.repair-manual',input:{}})`)
  await click('执行修复')
  await wait(`!!document.getElementById('本地项目')`)
  assert.equal(await evaluate(`[...document.querySelectorAll('button')].find(b=>b.textContent==='创建聊天并发送').disabled`), true)
  await evaluate(`(()=>{const select=document.getElementById('本地项目');select.value='local-fixture';select.dispatchEvent(new Event('change',{bubbles:true}))})()`)
  assert.equal(await evaluate(`[...document.querySelectorAll('button')].find(b=>b.textContent==='创建聊天并发送').disabled`), false)
  await screenshot('ones-repair-manual', 'light', 360)
  await click('创建聊天并发送')
  await wait(`document.body.innerText.includes('session-fixture-only')`)
  return { manualFallback: true, dualEntry: true, topRight: geometry, autoMapping: true, receipt: true, bottomEntry: true, missingSessionNavigationExplained: true }
}
