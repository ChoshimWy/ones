import assert from 'node:assert/strict'
// 仅针对隔离 profile 中的虚构 Worker；不能指向生产账号。
export async function exerciseStatusUpdate({ evaluate, wait, screenshot }) {
  const click = label => evaluate(`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent===${JSON.stringify(label)});if(!b||b.disabled)throw Error('Unavailable button: '+${JSON.stringify(label)});b.click()})()`)
  const fill = (label, value, event = 'input') => evaluate(`(()=>{const f=document.getElementById(${JSON.stringify(label)});if(!f||f.disabled)throw Error('Unavailable field');f.value=${JSON.stringify(value)};f.dispatchEvent(new Event(${JSON.stringify(event)},{bubbles:true}))})()`)
  await evaluate(`document.querySelector('button.bug-item').click()`)
  await wait(`[...document.querySelectorAll('button')].some(b=>b.textContent==='更新状态'&&!b.disabled)`)
  await click('执行修复')
  await wait(`document.body.innerText.includes('自动匹配：本地虚构项目')`)
  await click('创建聊天并发送')
  await wait(`document.body.innerText.includes('session-fixture-only')`)
  await click('更新状态')
  await fill('流转步骤', 'fix', 'change')
  await fill('解决方法（可粘贴修复总结）', '会话报告：已调整状态刷新，但实体设备尚未复测。<script>不可执行</script>\n长总结：'.repeat(7))
  await fill('交付情况（未提交 / 未合并 / 未发布请保留）', '未提交、未合并、未发布')
  await click('预览状态更新')
  await wait(`!!document.querySelector('[role=alert]')`)
  await screenshot('ones-status-required-error', 'light', 360)
  await fill('根因 *（必填）', 'logic', 'change')
  await fill('解决版本', 'v-next-user-confirmed')
  await screenshot('ones-status-form-dark', 'dark', 460)
  assert.equal(await evaluate(`document.documentElement.scrollWidth>innerWidth`), false)
  await click('预览状态更新')
  await wait(`!!document.querySelector('[data-status-preview]')`)
  await evaluate(`document.querySelector('[data-status-preview]').scrollIntoView()`)
  await screenshot('ones-status-preview-light', 'light', 360)
  assert.equal(await evaluate(`document.body.innerText.includes('未提交、未合并、未发布') && !window.externalContentExecuted`), true)
  await evaluate(`orca.host.call('plugin.request',{name:'fixture.transition-mode',input:{mode:'hold'}})`)
  await click('确认更新状态')
  await wait(`document.body.innerText.includes('离开详情不会撤销')`)
  assert.equal(await evaluate(`[...document.querySelectorAll('[data-status-preview] button')].every(b=>b.disabled)`), true)
  await screenshot('ones-status-submitting', 'dark', 460)
  await evaluate(`orca.host.call('plugin.request',{name:'fixture.transition-mode',input:{mode:'unknown'}})`)
  await evaluate(`orca.host.call('plugin.request',{name:'fixture.transition-release',input:{}})`)
  await wait(`document.body.innerText.includes('结果待核实') && [...document.querySelectorAll('button')].some(b=>b.textContent==='核对结果'&&!b.disabled)`)
  await evaluate(`document.querySelector('body').scrollIntoView()`)
  await screenshot('ones-status-unknown', 'dark', 360)
  await click('刷新详情')
  await wait(`document.body.innerText.includes('结果待核实') && document.body.innerText.includes('session-fixture-only')`)
  assert.equal(await evaluate(`[...document.querySelectorAll('button')].some(b=>b.textContent==='确认更新状态')`), false)
  await click('核对结果')
  await wait(`document.body.innerText.includes('更新成功') && document.body.innerText.includes('媒体验证项目 · 已修复') && document.body.innerText.includes('session-fixture-only')`)
  await screenshot('ones-status-success', 'light', 460)
  await evaluate(`document.querySelectorAll('section.card').forEach(c=>{if(c.querySelector('h2')?.textContent==='相关评论')c.scrollIntoView()})`)
  await screenshot('ones-status-comment', 'dark', 360)
  assert.equal(await evaluate(`document.body.innerText.includes('说明来源：用户手动填写/粘贴；非插件独立验证。') && document.body.innerText.includes('正文末尾')`), true)
  await click('返回我的 Bug')
  await wait(`document.body.innerText.includes('已读取') || document.body.innerText.includes('筛选')`)
  assert.equal(await evaluate(`document.querySelectorAll('button.bug-item').length`), 0)
  const calls = await evaluate(`orca.host.call('plugin.request',{name:'fixture.calls',input:{}}).then(r=>r.output.value.calls)`)
  assert.equal(calls.filter(n=>n==='bugs.transitionSubmit').length, 1)
  assert.equal(calls.filter(n=>n==='repair.start').length, 1)
  assert.ok(calls.filter(n=>n==='bugs.list').length>=2)
  return { form: true, escapedSummary: true, requiredError: true, duplicateDisabled: true, unknownRefresh: true, successRefresh: true, commentRefresh: true, filteredRowRemoved: true, repairPreserved: true, writes: 1 }
}

// 仅补充焦点回退与真实 Tab 顺序，不重跑已通过的业务旅程。
export async function exerciseStatusKeyboard({ evaluate, wait, screenshot, press }) {
  await evaluate(`document.querySelector('button.bug-item').click()`)
  await wait(`[...document.querySelectorAll('button')].some(b=>b.textContent==='更新状态'&&!b.disabled)`)
  await evaluate(`[...document.querySelectorAll('button')].find(b=>b.textContent==='更新状态').click()`)
  assert.equal(await evaluate(`document.activeElement?.id`), '流转步骤')
  await evaluate(`[...document.querySelectorAll('button')].find(b=>b.textContent==='收起状态表单').click()`)
  assert.equal(await evaluate(`document.activeElement?.textContent`), '更新状态')
  await screenshot('ones-status-focus-return', 'light', 360)
  await press('Tab')
  assert.equal(await evaluate(`document.activeElement?.textContent`), '执行修复')
  return { openFocus: true, closeFocusReturned: true, nativeTabOrder: true }
}
